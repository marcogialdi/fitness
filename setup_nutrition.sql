-- Tabella alimentazione (export "Daily Summary" di Cronometer). Esegui una volta in Supabase > SQL Editor.
-- Una riga per giorno e per pasto (meal_group); la riga meal_group = 'Total' è il totale del giorno e alimenta i grafici.
-- Nomi colonna = intestazioni del CSV in minuscolo (µ -> u, spazi e parentesi -> _). Date -> log_date, Group -> meal_group.
create table if not exists public.nutrition_daily (
  id bigint generated always as identity primary key,
  log_date date not null,
  meal_group text not null,
  energy_kcal numeric,
  alcohol_g numeric,
  caffeine_mg numeric,
  oxalate_mg numeric,
  phytate_mg numeric,
  water_g numeric,
  b1_thiamine_mg numeric,
  b2_riboflavin_mg numeric,
  b3_niacin_mg numeric,
  b5_pantothenic_acid_mg numeric,
  b6_pyridoxine_mg numeric,
  b12_cobalamin_ug numeric,
  folate_ug numeric,
  vitamin_a_ug numeric,
  vitamin_c_mg numeric,
  vitamin_d_iu numeric,
  vitamin_e_mg numeric,
  vitamin_k_ug numeric,
  calcium_mg numeric,
  copper_mg numeric,
  iron_mg numeric,
  magnesium_mg numeric,
  manganese_mg numeric,
  phosphorus_mg numeric,
  potassium_mg numeric,
  selenium_ug numeric,
  sodium_mg numeric,
  zinc_mg numeric,
  net_carbs_g numeric,
  carbs_g numeric,
  fiber_g numeric,
  insoluble_fiber_g numeric,
  soluble_fiber_g numeric,
  starch_g numeric,
  sugars_g numeric,
  added_sugars_g numeric,
  fat_g numeric,
  cholesterol_mg numeric,
  monounsaturated_g numeric,
  polyunsaturated_g numeric,
  saturated_g numeric,
  trans_fats_g numeric,
  omega_3_g numeric,
  ala_g numeric,
  dha_g numeric,
  epa_g numeric,
  omega_6_g numeric,
  aa_g numeric,
  la_g numeric,
  cystine_g numeric,
  histidine_g numeric,
  isoleucine_g numeric,
  leucine_g numeric,
  lysine_g numeric,
  methionine_g numeric,
  phenylalanine_g numeric,
  protein_g numeric,
  threonine_g numeric,
  tryptophan_g numeric,
  tyrosine_g numeric,
  valine_g numeric,
  completed boolean,
  created_at timestamptz not null default now(),
  constraint nutrition_daily_log_date_meal_group_key unique (log_date, meal_group)
);

-- Lettura pubblica (grafici) e scrittura riservata agli utenti autenticati, come per le altre tabelle.
alter table public.nutrition_daily enable row level security;
drop policy if exists "lettura pubblica" on public.nutrition_daily;
create policy "lettura pubblica" on public.nutrition_daily for select to anon, authenticated using (true);
drop policy if exists "scrittura autenticati" on public.nutrition_daily;
create policy "scrittura autenticati" on public.nutrition_daily for all to authenticated using (true) with check (true);
